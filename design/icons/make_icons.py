def build(text):
    grid = rows(text)
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y, ln in enumerate(grid):
        for x, ch in enumerate(ln):
            if ch != ".":
                c = PAL[ch]
                px[x, y] = (int(c[:2], 16), int(c[2:4], 16), int(c[4:], 16), 255)
    src = im.copy().load()
    # 1px ink outline on the four sides, never on top of a filled pixel.
    for y in range(16):
        for x in range(16):
            if src[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < 16 and 0 <= ny < 16 and src[nx, ny][3]:
                    px[x, y] = INK
                    break
    return im


def main():
    for folder, table in (("kit", KIT), ("list", LIST)):
        (OUT / folder).mkdir(parents=True, exist_ok=True)
        for name, text in table.items():
            build(text).save(OUT / folder / f"{name}.png")
    # "crystal" is the same art as "vanilla": lists use both names for that gamemode.
    build(KIT["vanilla"]).save(OUT / "kit/crystal.png")
    print(len(KIT) + 1, "kit icons,", len(LIST), "list marks ->", OUT)


if __name__ == "__main__":
    main()
