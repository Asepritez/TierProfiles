def rows(text):
    r = [ln.strip() for ln in text.strip("\n").split("\n")]
    assert len(r) == 16, f"need 16 rows, got {len(r)}"
    for ln in r:
        assert len(ln) == 16, f"bad row {ln!r} ({len(ln)})"
    return r


